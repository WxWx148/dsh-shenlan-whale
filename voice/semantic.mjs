/**
 * voice/semantic.mjs — 按语义断句，不按字数硬切。
 *
 * ══════════════════════════════════════════════════════════════
 * 【为什么要有这一层】
 *
 *   聊天里最难看的一种发法，是把话从中间劈开：
 *
 *     「搜出来的全是百科和官网首页，没有一条真新」   ← 断在「真新」
 *     「的」                                        ← 这条谁看都难受
 *     「老大给我的搜索源太差，换我我也不好意思交」   ← 断在「交」
 *     「差」
 *
 *   毛病不在切的位置「偏了几字」，在于**切出来的不是一句能站住的话**。
 *   「的」「差」这种词，单独发出来在聊天里是没有意义的碎片。
 *
 *   真人不这么发。真人断句找的是**语义边界**：
 *   在模型自己封的句子处断、在「我/你/但是/不过」这类能起头的地方断，
 *   实在找不到好地方，就**宁可发长一点**，也不切出碎片。
 *
 * ══════════════════════════════════════════════════════════════
 * 【这一层没有字数上限】
 *
 *   早先这里有一根「断句线」（每条多少字），到线就切 ——
 *   上面那两种碎片就是从那儿来的。用户后来明确说过：
 *
 *     「去掉字数限制，他想说多长说多长，只是尽量聊天拟人就好」
 *
 *   所以现在只有**下限**（别切出碎片），没有**上限**（爱说多长说多长）：
 *     · 句末标点（。！？）→ 模型自己封的句子，直接断；
 *     · 逗号 → 只有「前面那段站得住 + 后面那段能起头 + 两边都不算太短」才断；
 *     · 都没有 → 整段留着，不切。
 *
 *   下限不是「字数限制」的另一种写法：它拦的是「的」「差」这种**碎片**，
 *   不是长句。100 字的完整句子该发 100 字，2 个字的碎片不该单独发。
 *
 * ══════════════════════════════════════════════════════════════
 * 【怎么判断「这是个能站住的断点」】
 *
 *   两个条件，都满足才算：
 *     1. **切点前面**那段自己站得住（不是半个词）；
 *     2. **切点后面**那段能起头（不是「的」「差」「了」这种黏着词）。
 *
 *   第二个条件用**真实语料统计**出来的：
 *     本机群聊 800+ 条他人发言，按逗号切开后统计下一段的首字，
 *     最高频的是：我(45) 你(41) 是(13) 不(11) 没(9) 但(7) 还(7) 那(5) …
 *   这些是能起头的字。而「的」「地」「得」「了」「着」「过」这类是黏着词，
 *   跟在词尾的，切开就成碎片 —— 所以它们**前面不能断**。
 */

/** 黏着词：不能出现在一条的开头（它们只能跟在词尾） */
export const STICKY = new Set([
  '的', '地', '得', '了', '着', '过', '们', '么', '呢', '吧', '啊', '呀', '嘛', '哦', '哈', '嗯',
  '而', '且', '就', '都', '也', '还', '又', '再', '很', '太', '最', '更', '挺', '蛮',
])

/**
 * **收尾**时不能出现的黏着词 —— 比 STICKY 窄得多。
 *
 * 为什么不能用同一张表：
 *   STICKY 管的是「能不能起头」，而「啊」「吧」「呢」「了」这些**能正常收尾**：
 *     「我先看看啊」「我知道」「行吧」「好的」—— 全是完整的话。
 *   拿它去判「前面那段站不站得住」，会把这些全判成「话没说完」，
 *   于是「我先看看啊，等会儿给你结果」这种该拆的永远拆不开（实测踩过）。
 *
 *   真正「说了还没说完」的只有这几个：的（真新的）、地、得（跑得快）、
 *   着（看着）、过（看过）、们（我们）。
 *
 * 注意「了」不在里面 —— 「我知道了」是完整的一句话。
 */
const TAIL_STICKY = new Set(['的', '地', '得', '着', '过', '们'])

/**
 * 能起头的字（真实语料统计出的高频字）。
 *
 * 为什么只收这一批、而不是「所有不是黏着词的字」：
 *   收得越宽，判定越松，松了就会切出「这句话还行」「那个东西」这种
 *   勉强能看但其实断得不好的地方。收窄一点，宁可不断。
 */
const STARTERS = new Set([
  '我', '你', '他', '她', '它', '咱', '您', '谁', '什', '怎', '哪', '这', '那', '哪', '有', '没',
  '是', '不', '也', '在', '要', '会', '能', '可', '就', '还', '再', '又', '但', '不', '可',
  '想', '觉', '看', '听', '说', '问', '回', '给', '让', '叫', '帮', '找', '弄', '搞', '做',
  '如', '果', '因', '所', '但', '虽', '然', '而', '否', '则', '并', '且', '或', '跟', '同',
  '一', '两', '三', '几', '个', '点', '先', '再', '现', '今', '明', '昨', '早', '晚', '夜',
  '今', '过', '刚', '还', '已', '正', '在', '别', '快', '慢', '多', '少', '长', '短', '大', '小',
  '上', '下', '左', '右', '里', '外', '前', '后', '中', '内', '间', '边', '头', '面',
])

/** 句子末尾的标点：判断「站不站得住」时要先把它摘掉 */
const TAIL_PUNCT = /[，,、；;：:。．.!！?？…]+$/u

/**
 * 断点前面那一段自己站不站得住。
 *
 * 判据：结尾不能是「话还没说完」的黏着词（「真新的」不行，「真新闻」行）。
 *
 * 注意要先摘掉句末标点：断点前面那段的最后一个字往往是逗号，
 * 直接看最后一个字的话，逗号永远「站得住」，这道检查就形同虚设。
 *
 * @param {string} chunk 断点前的那段
 * @returns {boolean}
 */
export function standsAlone(chunk) {
  const text = String(chunk || '').trim().replace(TAIL_PUNCT, '')
  if (!text) return false
  const last = text[text.length - 1]
  // 结尾是黏着词 → 这段还没说完，不能在这断
  return !TAIL_STICKY.has(last)
}

/**
 * 断点后面那一段能不能起头。
 *
 * @param {string} chunk 断点后的那段
 * @returns {boolean}
 */
export function canStart(chunk) {
  const text = String(chunk || '').trim()
  if (!text) return false
  const first = text[0]
  // 开头是黏着词 → 这段是上一句的尾巴，不能起头
  if (STICKY.has(first)) return false
  // 开头是人称代词这类能起头的字 → 行
  if (STARTERS.has(first)) return true
  // 其他字：数字、字母、引号后的内容等，也算能起头
  // （中文里绝大多数实词都能起头，收窄只是为了避开黏着词）
  return true
}

/**
 * 在一段文字里找最好的断点。
 *
 * 找的顺序（先找到的优先）：
 *   1. **句末标点** —— 模型自己封的句子，边界最硬，后面能起头就断；
 *   2. **逗号/顿号** —— 次强，但要看前后两边能不能站住、够不够长；
 *   3. **没有好断点** —— 返回 -1，意思是「别切，宁可整段留着」。
 *
 * 跟早先那版最大的不同：**没有字数窗口**。
 *   早先要传 limit（断句线），到线就找断点，找不到就硬切 ——
 *   于是「真新 / 的」这种碎片就是这么来的。现在整段一起看，
 *   哪儿顺在哪儿断；哪儿都不顺，就不断。
 *
 * @param {string} text
 * @param {object} [options]
 * @param {number} [options.minHead] 逗号断开时，前半段至少这么长（去掉标点后算）
 * @param {number} [options.minTail] 逗号断开时，后半段至少这么长
 * @returns {number} 断点位置（切在它前面）；-1 = 没有好断点
 */
export function findBreak(text, options = {}) {
  const body = String(text || '')
  if (!body) return -1
  const minHead = Math.max(1, Number(options.minHead) || 4)
  const minTail = Math.max(1, Number(options.minTail) || 4)

  for (let i = 0; i < body.length; i += 1) {
    const ch = body[i]
    // 句末标点：模型自己封的句子，边界最硬。
    // 后面只要不是「的」「差」这种黏着词的尾巴，就断。
    if (/[。！？!?]/.test(ch)) {
      const tail = body.slice(i + 1).trim()
      if (!tail) return -1 // 后面没话了 → 这里不是断点，整段留着
      if (!canStart(tail)) continue // 后面是上一句的尾巴 → 不断
      return i + 1
    }
    if (!/[，,、；;：:]/.test(ch)) continue
    // 逗号：两边都得站得住，而且都得够长。
    //
    // 「够长」是下限不是上限：两三字的碎片单独发出去，在聊天里是最难看的一种；
    // 三十字的完整句子就该发三十字。
    const head = body.slice(0, i + 1)
    const tail = body.slice(i + 1).trim()
    const headText = head.replace(TAIL_PUNCT, '').trim()
    if (headText.length < minHead) continue
    if (tail.length < minTail) continue
    if (!standsAlone(head)) continue
    if (!canStart(tail)) continue
    return i + 1
  }

  // 没有好断点
  return -1
}

/**
 * 按语义把一段话切成若干条。
 *
 * 与「按字数硬切」的区别：
 *   · 硬切：到字数就切，不管切出来的是不是一句完整的话；
 *   · 语义切：只在能站住的地方切，切不出好断点就**不切**（宁可长）。
 *
 * 切出来的每一段都**保留原来的标点**（逗号、句号都在）。
 *   抹标点交给调用方做 —— 因为合并成一条的时候，那些标点正好是
 *   「这里本来有道缝」的证据，抹早了接回去就成了一坨。
 *
 * @param {string} text
 * @param {object} [options]
 * @param {number} [options.minHead] 逗号断开时，前半段至少这么长
 * @param {number} [options.minTail] 逗号断开时，后半段至少这么长
 * @returns {string[]}
 */
export function splitByMeaning(text, options = {}) {
  const body = String(text || '').trim()
  if (!body) return []
  const minHead = Math.max(1, Number(options.minHead) || 4)
  const minTail = Math.max(1, Number(options.minTail) || 4)

  const out = []
  let rest = body
  while (rest) {
    const cut = findBreak(rest, { minHead, minTail })
    // 没有好断点 → 不切。宁可这一条长一点，也不要切出碎片。
    if (cut <= 0) break
    const head = rest.slice(0, cut).trim()
    const tail = rest.slice(cut).trim()
    if (!head || !tail) break
    out.push(head)
    rest = tail
  }
  if (rest) out.push(rest)
  return out.filter(Boolean)
}
